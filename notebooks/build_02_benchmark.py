def gap_ci(a, b, n=10_000):
    d = (wide[a] - wide[b]).to_numpy()
    boots = d[rng.integers(0, len(d), (n, len(d)))].mean(axis=1) * 100
    return d.mean() * 100, *np.percentile(boots, [2.5, 97.5])
